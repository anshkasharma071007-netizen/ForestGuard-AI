from __future__ import annotations

from datetime import timedelta

from sqlalchemy import select
from sqlalchemy.orm import Session

from geospatial.mapping import haversine_km, polygon_ring
from geospatial.risk_analysis import RiskSettings, villages_within_radius
from geospatial.species import species_meta

from backend.models import Alert, AlertEvent, Detection, Guard, Village, utcnow

SEVERITY_HIGH = 65.0
SEVERITY_CRITICAL = 80.0


def village_dicts(db: Session) -> list[dict]:
    villages = db.scalars(select(Village)).all()
    return [
        {
            "id": village.id,
            "name": village.name,
            "lat": village.lat,
            "lon": village.lon,
            "population": village.population,
            "boundary_ring": polygon_ring(village.boundary_geojson),
        }
        for village in villages
    ]


def _nearest_guard(db: Session, lat: float, lon: float) -> Guard | None:
    guards = db.scalars(select(Guard).where(Guard.status != "off_duty")).all()
    if not guards:
        return None
    return min(guards, key=lambda guard: haversine_km(lat, lon, guard.lat, guard.lon))


def _severity(score: float) -> tuple[str, int]:
    if score >= SEVERITY_CRITICAL:
        return "high", 1
    if score >= SEVERITY_HIGH:
        return "high", 2
    return "moderate", 3


def _public_summary(species: str, severity: str, village_names: list[str]) -> str:
    meta = species_meta(species)
    where = ", ".join(village_names[:2]) if village_names else "a buffer-zone settlement"
    level = "High-priority" if severity == "high" else "Precautionary"
    return (
        f"{level} advisory: {meta['name']} activity reported near {where}. "
        f"Follow forest-department safety guidance and avoid travelling on forest roads after dusk. "
        f"{meta['advice']}"
    )


def _has_recent_duplicate(db: Session, detection: Detection, villages: list[dict]) -> bool:
    since = detection.detected_at - timedelta(hours=24)
    recent = db.scalars(
        select(Alert).where(
            Alert.species == detection.species,
            Alert.created_at >= since,
            Alert.status != "resolved",
        )
    ).all()
    new_village_ids = {v["id"] for v in villages}
    for alert in recent:
        if set(alert.village_ids or []) & new_village_ids:
            return True
        if detection.nearest_village_id and detection.nearest_village_id in (alert.village_ids or []):
            return True
    return False


def maybe_create_alert(
    db: Session,
    detection: Detection,
    risk: dict,
    settings: RiskSettings,
    *,
    actor: str = "Risk engine",
) -> Alert | None:
    threshold = float(settings.data["alert_threshold"])
    if risk["score"] < threshold:
        return None
    villages = villages_within_radius(
        detection.lat, detection.lon, village_dicts(db), float(settings.data["alert_radius_km"])
    )
    if not villages:
        return None
    if _has_recent_duplicate(db, detection, villages):
        return None

    severity, priority = _severity(risk["score"])
    village_names = [v["name"] for v in villages]
    created_at = detection.detected_at + timedelta(minutes=2)
    alert = Alert(
        detection_id=detection.id,
        species=detection.species,
        severity=severity,
        score=risk["score"],
        risk_basis=risk["basis"],
        reason=risk["reason"],
        village_ids=[v["id"] for v in villages],
        radius_km=float(settings.data["alert_radius_km"]),
        status="active",
        priority_rank=priority,
        public_summary=_public_summary(detection.species, severity, village_names),
        is_simulated=detection.is_simulated,
        created_at=created_at,
    )
    guard = _nearest_guard(db, detection.lat, detection.lon)
    if guard:
        alert.assigned_guard_id = guard.id
    db.add(alert)
    db.flush()
    db.add(
        AlertEvent(
            alert_id=alert.id,
            kind="generated",
            note=f"Alert generated by the risk engine (score {risk['score']:.1f}, {risk['basis_label']}).",
            actor=actor,
            created_at=created_at,
        )
    )
    if guard:
        db.add(
            AlertEvent(
                alert_id=alert.id,
                kind="assigned",
                note=f"Assigned to {guard.name} ({guard.badge_id}) based on proximity.",
                actor="Dispatch",
                created_at=created_at + timedelta(minutes=1),
            )
        )
    for village in db.scalars(select(Village).where(Village.id.in_([v["id"] for v in villages]))):
        village.last_alert_at = detection.detected_at
    db.flush()
    return alert


def sync_alerts(db: Session, settings: RiskSettings, *, days: int = 30) -> list[Alert]:
    since = utcnow() - timedelta(days=days)
    detections = db.scalars(
        select(Detection).where(Detection.detected_at >= since).order_by(Detection.detected_at)
    ).all()
    created = []
    for det in detections:
        if det.risk_score < float(settings.data["alert_threshold"]):
            continue
        risk = {
            "score": det.risk_score,
            "basis": det.risk_basis or "proximity",
            "basis_label": "Movement-supported" if det.risk_basis == "confirmed_movement" else "Proximity-based",
            "reason": _reason_for(det),
        }
        alert = maybe_create_alert(db, det, risk, settings)
        if alert:
            created.append(alert)
    db.commit()
    return created


def _reason_for(detection: Detection) -> str:
    meta = species_meta(detection.species)
    village = detection.nearest_village.name if detection.nearest_village else "the nearest village"
    distance = detection.observed_distance_km
    distance_text = f"{distance:.1f} km" if distance is not None else "an unspecified distance"
    return (
        f"{meta['name']} detection {distance_text} from {village} boundary. "
        "Open the detection record for the full, explainable risk breakdown."
    )
