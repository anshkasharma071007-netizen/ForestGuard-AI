"""Generate annotated evidence images for the seeded demonstration dataset.

Run from the repository root after installing the AI dependencies:
    python demo_data/build_detection_assets.py

The output images are real photographs (see docs/references/image_credits.md)
that have been processed by the AI engine. They are representative evidence
for a synthetic demonstration dataset — they are not real camera-trap events.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile

from PIL import Image, ImageEnhance, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from ai_engine.detector import get_engine  # noqa: E402
RAW = os.path.join(ROOT, "demo_data", "wildlife_images")
OUT = os.path.join(ROOT, "demo_data", "detection_images")
MANIFEST = os.path.join(ROOT, "demo_data", "detection_assets.json")
SPECIES = ["tiger", "leopard", "elephant", "deer", "wild_boar", "sloth_bear"]


def variant_two(source: str, target: str) -> None:
    image = Image.open(source).convert("RGB")
    width, height = image.size
    crop = int(min(width, height) * 0.06)
    image = image.crop((crop, crop, width - crop, height - crop))
    image = ImageOps.mirror(image)
    image = ImageEnhance.Contrast(image).enhance(1.04)
    image.save(target, "JPEG", quality=90, optimize=True)


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    engine = get_engine()
    items = []
    with tempfile.TemporaryDirectory() as tmp:
        source_names = {
            "wild_boar": "boar.jpg",
            "sloth_bear": "bear.jpg",
        }
        for species in SPECIES:
            source = os.path.join(RAW, source_names.get(species, f"{species}.jpg"))
            if not os.path.exists(source):
                print("skip missing", source)
                continue
            for variant in (1, 2):
                work = os.path.join(tmp, f"{species}_{variant}.jpg")
                if variant == 1:
                    shutil.copyfile(source, work)
                else:
                    variant_two(source, work)
                result = engine.analyze_image(
                    work,
                    save_annotated=False,
                    footer="FOREST GUARD AI · demonstration evidence · not a field observation",
                )
                identified = [d for d in result["detections"] if d["is_species_confident"]]
                if not identified:
                    print("no confident detection", species, variant, result["detections"])
                    continue
                best = identified[0]
                annotated = os.path.join(OUT, f"{species}_{variant}_annotated.jpg")
                from ai_engine.annotate import draw_detections

                draw_detections(
                    work,
                    [best],
                    annotated,
                    footer="FOREST GUARD AI · demonstration evidence · not a field observation",
                )
                with Image.open(work) as im:
                    width, height = im.size
                items.append(
                    {
                        "key": species,
                        "variant": variant,
                        "image": os.path.basename(annotated),
                        "species": best["species"],
                        "confidence": best["confidence"],
                        "species_confidence": best["species_confidence"],
                        "detector_confidence": best["detector_confidence"],
                        "bbox": best["bbox"],
                        "width": width,
                        "height": height,
                        "is_simulated": True,
                        "note": "Annotated demonstration evidence generated by the AI engine; not a real camera-trap event.",
                    }
                )
                print("ok", species, variant, best["species"], best["confidence"])

    payload = {
        "generated_with": "YOLO-World v2 + CLIP zero-shot classification",
        "disclaimer": (
            "Representative annotated images for the synthetic demonstration dataset. "
            "Image credits are documented in docs/references/image_credits.md."
        ),
        "items": items,
    }
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
    print("wrote", MANIFEST, len(items), "assets")


if __name__ == "__main__":
    main()
